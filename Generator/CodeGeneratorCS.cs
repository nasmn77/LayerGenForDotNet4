                W(sb, 3, "var ds = new DataSet();");
                W(sb, 3, "da.Fill(ds);");
                W(sb, 3, "return ds.Tables.Count > 0 && ds.Tables[0].Rows.Count > 0 ? ds.Tables[0] : null;");
