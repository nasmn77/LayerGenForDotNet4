        public static string GenerateStoredProcedures(TableInfo table, bool suppressComments, bool falseErase, string falseEraseField, string schema = "dbo")
        {
            var sb = new StringBuilder();
            string tbl = table.TableName;
            string pk = table.PrimaryKey ?? "";
            var pkField = pk != "" ? table.Fields.FirstOrDefault(f => f.FieldName == pk) : null;

            void Line(string s = "") => sb.AppendLine(s);
            string sch = $"[{(string.IsNullOrWhiteSpace(schema) ? "dbo" : schema)}]";
            string genDate = DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss");
            void SpHeader()
            {
                Line("-- ===========================================================================");
                Line("-- This file was generated by LayerGenForDotNet4 application");
                Line($"-- Generated on: {genDate}");
                Line("-- Naser Almadi");
                Line("-- nasmn77@gmail.com");
                Line("-- ===========================================================================");
            }
            void DropCreate(string procName)
            {
                Line($"IF EXISTS (SELECT * FROM sys.objects WHERE type = 'P' AND name = '{procName}')");
                Line($"    DROP PROCEDURE {sch}.[{procName}]");
                Line("GO");
                Line();
            }
            void GoGrant(string procName)
            {
                Line("GO");
                Line("-- ======= Permissions =======");
                Line($"GRANT EXECUTE ON {sch}.[{procName}] TO [public]");
                Line("GO");
                Line();
            }

            // ── SELECT ────────────────────────────────────────────────────────────
            if (pk != "" && pkField != null)
            {
                string procSelect = SpName(tbl, "Select");
                DropCreate(procSelect);
                if (!suppressComments) Line($"-- SELECT one record from {tbl} by primary key");
                SpHeader();
                Line($"CREATE PROCEDURE {sch}.[{procSelect}]");
                Line($"    @{pk} {GetSqlTypeDecl(pkField)} = NULL");
                Line("AS");
                Line("SET NOCOUNT ON;");
                Line($"SELECT {BuildSelectColumns(table.Fields)}");
                Line($"FROM {sch}.[{tbl}]");
                Line($"WHERE [{pk}] = @{pk}");
                GoGrant(procSelect);
            }

            // ── INSERT ────────────────────────────────────────────────────────────
            if (!table.IsView)
            {
                string procInsert = SpName(tbl, "Insert");
                DropCreate(procInsert);
                if (!suppressComments) Line($"-- INSERT a new record into {tbl}");
                SpHeader();
                Line($"CREATE PROCEDURE {sch}.[{procInsert}]");

                // Insert params: exclude FalseErase field (always hardcoded to 0 in INSERT, never a parameter)
                bool hasFEField = falseEraseField != "" && table.Fields.Any(f => f.FieldName.Equals(falseEraseField, StringComparison.OrdinalIgnoreCase));
                var insertParams = table.Fields
                    .Where(f => !f.IsComputed &&
                        !(hasFEField && f.FieldName.Equals(falseEraseField, StringComparison.OrdinalIgnoreCase)))
                    .ToList();

                bool first = true;
                foreach (var f in insertParams)
                {
                    string prefix = first ? "    " : "   ,";
                    first = false;
                    bool isOutputPk = f.IsPrimaryKey && table.IsPrimaryKeyIdentity;
                    string outStr = isOutputPk ? " OUTPUT" : "";
                    string nullDefault = (!isOutputPk && f.IsNullable) ? " = NULL" : "";
                    Line($"{prefix}@{f.FieldName} {GetSqlTypeDecl(f)}{outStr}{nullDefault}");
                }
                Line("AS");
                Line("SET NOCOUNT ON;");
                Line();

                // Columns to insert: exclude identity PK; FalseErase col gets hardcoded value 0
                var nonIdentityCols = table.Fields
                    .Where(f => !f.IsComputed && !(f.IsPrimaryKey && table.IsPrimaryKeyIdentity))
                    .ToList();

                // FalseErase column: NOT a parameter – written inline as literal 0 in VALUES
                var insertCols = nonIdentityCols
                    .Where(f => !(hasFEField && f.FieldName.Equals(falseEraseField, StringComparison.OrdinalIgnoreCase)))
                    .Select(f => $"[{f.FieldName}]");
                var insertVals = nonIdentityCols
                    .Where(f => !(hasFEField && f.FieldName.Equals(falseEraseField, StringComparison.OrdinalIgnoreCase)))
                    .Select(f => $"@{f.FieldName}");

                string feCols = hasFEField ? $", [{falseEraseField}]" : "";
                string feVals = hasFEField ? ", 0" : "";

                Line($"INSERT INTO {sch}.[{tbl}]");
                Line($"    ({string.Join(", ", insertCols)}{feCols})");
                Line("VALUES");
                Line($"    ({string.Join(", ", insertVals)}{feVals})");
                Line();
                if (pk != "" && table.IsPrimaryKeyIdentity)
                    Line($"SET @{pk} = SCOPE_IDENTITY()");
                GoGrant(procInsert);

                // ── UPDATE ────────────────────────────────────────────────────────
                string procUpdate = SpName(tbl, "Update");
                DropCreate(procUpdate);
                if (!suppressComments) Line($"-- UPDATE an existing record in {tbl}");
                SpHeader();
                Line($"CREATE PROCEDURE {sch}.[{procUpdate}]");

                // Exclude FalseErase field from Update – it is managed only by Delete
                first = true;
                foreach (var f in table.Fields.Where(f => !f.IsComputed &&
                    !(hasFEField && f.FieldName.Equals(falseEraseField, StringComparison.OrdinalIgnoreCase))))
                {
                    string prefix = first ? "    " : "   ,";
                    first = false;
                    string nullDefault = (!f.IsPrimaryKey && f.IsNullable) ? " = NULL" : "";
                    Line($"{prefix}@{f.FieldName} {GetSqlTypeDecl(f)}{nullDefault}");
                }
                Line("AS");
                Line("SET NOCOUNT ON;");
                Line();
                Line($"UPDATE {sch}.[{tbl}]");
                Line("SET");
                var updateFields = table.Fields
                    .Where(f => !f.IsComputed && !f.IsPrimaryKey &&
                        !(hasFEField && f.FieldName.Equals(falseEraseField, StringComparison.OrdinalIgnoreCase)))
                    .ToList();
                for (int i = 0; i < updateFields.Count; i++)
                {
                    string sep = i < updateFields.Count - 1 ? "," : "";
                    Line($"    [{updateFields[i].FieldName}] = @{updateFields[i].FieldName}{sep}");
                }
                if (pk != "")
                    Line($"WHERE [{pk}] = @{pk}");
                GoGrant(procUpdate);
            }

            // ── DELETE ────────────────────────────────────────────────────────────
            if (pk != "" && pkField != null && !table.IsView)
            {
                string procDelete = SpName(tbl, "Delete");
                DropCreate(procDelete);
                if (!suppressComments) Line($"-- DELETE a record from {tbl}");
                SpHeader();
                Line($"CREATE PROCEDURE {sch}.[{procDelete}]");
                Line($"    @{pk} {GetSqlTypeDecl(pkField)} = NULL");
                Line("AS");
                Line("SET NOCOUNT ON;");
                if (falseErase && falseEraseField != "")
                {
                    // Soft delete: set the FalseErase field to 1
                    Line($"UPDATE {sch}.[{tbl}] SET [{falseEraseField}] = 1 WHERE [{pk}] = @{pk}");
                }
                else
                {
                    Line($"DELETE FROM {sch}.[{tbl}] WHERE [{pk}] = @{pk}");
                }
                GoGrant(procDelete);
            }

            // ── GET ALL ───────────────────────────────────────────────────────────
            {
                string procGetAll = SpName(tbl, "GetAll");
                DropCreate(procGetAll);
                if (!suppressComments) Line($"-- Get all records from {tbl}");
                SpHeader();
                Line($"CREATE PROCEDURE {sch}.[{procGetAll}]");
                Line("AS");
                Line("SET NOCOUNT ON;");
                Line($"SELECT {BuildSelectColumns(table.Fields)}");
                Line($"FROM {sch}.[{tbl}]");
                if (falseErase && falseEraseField != "")
                    Line($"WHERE [{falseEraseField}] = 0");
                GoGrant(procGetAll);
            }

            // ── GET BY FK ─────────────────────────────────────────────────────────
            foreach (var fk in table.ForeignKeys)
            {
                var fkColField = table.Fields.FirstOrDefault(f => f.FieldName.Equals(fk.FkColumn, StringComparison.OrdinalIgnoreCase));
                if (fkColField == null) continue;

                string procGetByFk = SpName(tbl, $"GetBy{fk.FkColumn}");
                DropCreate(procGetByFk);
                if (!suppressComments) Line($"-- Get all records from {tbl} where {fk.FkColumn} matches");
                SpHeader();
                Line($"CREATE PROCEDURE {sch}.[{procGetByFk}]");
                Line($"    @{fk.FkColumn} {GetSqlTypeDecl(fkColField)} = NULL");
                Line("AS");
                Line("SET NOCOUNT ON;");
                Line($"SELECT {BuildSelectColumns(table.Fields)}");
                Line($"FROM {sch}.[{tbl}]");
                if (falseErase && falseEraseField != "")
                    Line($"WHERE [{falseEraseField}] = 0 AND [{fk.FkColumn}] = @{fk.FkColumn}");
                else
                    Line($"WHERE [{fk.FkColumn}] = @{fk.FkColumn}");
                GoGrant(procGetByFk);
            }

            return sb.ToString();
        }

