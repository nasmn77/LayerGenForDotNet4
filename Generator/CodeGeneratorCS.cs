                    string ctype = f.CSharpType();
                    string baseType = ctype.TrimEnd('?');
                    W(sb, 4, $"{varName} = row[\"{f.FieldName}\"] == DBNull.Value ? ({ctype}){DefaultValueForFill(f)} : ({baseType})row[\"{f.FieldName}\"];");
