        /// <summary>
        /// ProperCase stored procedure name: sp_Tbl_1Test_Select
        /// Each segment capitalizes the first alphabetic character (after any leading digits).
        /// e.g. table "1test" → segment "1Test", table "tbl_1test" → "sp_Tbl_1Test_Select"
        /// </summary>
        private static string SpName(string tableName, string suffix)
        {
            string[] parts = tableName.Split('_');
            var sb2 = new StringBuilder();
            foreach (var p in parts)
            {
                sb2.Append('_');
                if (p.Length == 0) continue;
                // Find first alpha char and capitalize it; keep leading digits as-is
                bool capitalized = false;
                for (int i = 0; i < p.Length; i++)
                {
                    if (!capitalized && char.IsLetter(p[i]))
                    {
                        sb2.Append(char.ToUpperInvariant(p[i]));
                        capitalized = true;
                    }
                    else
                    {
                        sb2.Append(p[i]);
                    }
                }
            }
            return "sp" + sb2 + "_" + suffix;
        }

        private static string EscapeString(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");

        private static string BuildSelectColumns(List<FieldInfo> fields)
        {
            return string.Join(", ", fields.Select(f => $"[{f.FieldName}]"));
        }

        private static string GetSqlTypeDecl(FieldInfo f)
        {
            string t = f.SqlTypeName.ToLowerInvariant();
            return t switch
            {
                "nvarchar" or "varchar" => f.Length == -1 ? $"{t.ToUpper()}(MAX)" : $"{t.ToUpper()}({f.Length})",
                "nchar" or "char" => $"{t.ToUpper()}({f.Length})",
                "decimal" or "numeric" => $"{t.ToUpper()}({f.Precision},{f.Scale})",
                _ => t.ToUpper()
            };
        }

        private static string NullableParamValue(FieldInfo f, string varName)
            => CsParamValue(f, varName);

        /// <summary>
        /// C# parameter value expression:
        /// - Nullable types (string?, bool?, int?…) → (object?)var ?? DBNull.Value
        /// - NOT NULL value types (bool, int…)      → var  (always has a value)
        /// - NOT NULL string                         → (object?)var ?? DBNull.Value (defensive)
        /// </summary>
        private static string CsParamValue(FieldInfo f, string varName)
        {
            bool isRefType = f.NetType is SqlNetType.String or SqlNetType.ByteArray;
            // Nullable OR reference types → guard with DBNull
            if (f.IsNullable || isRefType)
                return $"(object?){varName} ?? DBNull.Value";
            // NOT NULL value type → send directly
            return varName;
        }

        private static string DefaultValueForFill(FieldInfo f)
        {
            if (f.IsNullable) return "null";
            return f.NetType switch
            {
                SqlNetType.String => "null",
                SqlNetType.ByteArray => "null",
                SqlNetType.Bool => "false",
                SqlNetType.Int or SqlNetType.Long or SqlNetType.Short or SqlNetType.Byte => "0",
                SqlNetType.Decimal => "0m",
                SqlNetType.Double => "0.0",
                SqlNetType.Float => "0f",
                SqlNetType.DateTime => "DateTime.MinValue",
                SqlNetType.TimeSpan => "TimeSpan.Zero",
                SqlNetType.Guid => "Guid.Empty",
                _ => "null"
            };
        }

