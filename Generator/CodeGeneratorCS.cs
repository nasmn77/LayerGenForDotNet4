                    W(sb, 5, $"{varName} = ({baseType})row[\"{f.FieldName}\"];");
                }

                if (f.IsPrimaryKey)
                    W(sb, 5, "_isUpdate = true;");

                W(sb, 4, "}");
                W(sb, 4, "else");
                W(sb, 4, "{");
