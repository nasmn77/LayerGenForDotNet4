                W(sb, 3, "cmd.Connection = conn;");
                W(sb, 3, "cmd.CommandType = CommandType.StoredProcedure;");
                W(sb, 0);

                // Add parameters – exclude FalseErase field and identity PK
                foreach (var f in table.Fields)
                {
                    if (f.IsComputed) continue;
                    if (f.IsPrimaryKey && table.IsPrimaryKeyIdentity) continue;
                    if (hasFEField && f.FieldName.Equals(falseEraseField, StringComparison.OrdinalIgnoreCase)) continue;

                    string varName = $"_{SafeName(f.FieldName)}";
                    string sqlDbType = f.SqlDbTypeStr();
                    string ftLow = f.SqlTypeName.ToLowerInvariant();
                    string paramVal = CsParamValue(f, varName);

                    if (ftLow is "decimal" or "numeric")
                        W(sb, 3, $"{{ var _p = cmd.Parameters.Add(\"@{f.FieldName}\", SqlDbType.{sqlDbType}); _p.Precision = {f.Precision}; _p.Scale = {f.Scale}; _p.Value = {paramVal}; }}");
                    else if (ftLow is "nvarchar" or "varchar" or "char" or "nchar")
                    {
                        int sz = f.Length == -1 ? -1 : f.Length;
                        W(sb, 3, $"cmd.Parameters.Add(\"@{f.FieldName}\", SqlDbType.{sqlDbType}, {sz}).Value = {paramVal};");
                    }
                    else
                        W(sb, 3, $"cmd.Parameters.Add(\"@{f.FieldName}\", SqlDbType.{sqlDbType}).Value = {paramVal};");
                }

                // PK parameter
                if (hasPk && pkField2 != null)
                {
                    if (table.IsPrimaryKeyIdentity)
                        W(sb, 3, $"cmd.Parameters.Add(\"@{pkField2.FieldName}\", SqlDbType.{pkField2.SqlDbTypeStr()}).Direction = ParameterDirection.Output;");
                    else
                        W(sb, 3, $"cmd.Parameters.Add(\"@{pkField2.FieldName}\", SqlDbType.{pkField2.SqlDbTypeStr()}).Value = _{SafeName(pkField2.FieldName)};");
                }

                W(sb, 0);
                string spInsert = SpName(table.TableName, "Insert");
                string spUpdate = SpName(table.TableName, "Update");
                W(sb, 3, "if (_isUpdate)");
                W(sb, 3, "{");
                W(sb, 4, $"cmd.CommandText = \"[dbo].[{spUpdate}]\";");
                if (hasPk && pkField2 != null && !table.IsPrimaryKeyIdentity)
                    W(sb, 4, $"cmd.Parameters[\"@{pkField2.FieldName}\"].Direction = ParameterDirection.Input;");
                W(sb, 3, "}");
                W(sb, 3, "else");
                W(sb, 3, "{");
                W(sb, 4, $"cmd.CommandText = \"[dbo].[{spInsert}]\";");
                if (hasPk && pkField2 != null && table.IsPrimaryKeyIdentity)
                    W(sb, 4, $"cmd.Parameters[\"@{pkField2.FieldName}\"].Direction = ParameterDirection.Output;");
                else if (hasPk && pkField2 != null)
                    W(sb, 4, $"cmd.Parameters[\"@{pkField2.FieldName}\"].Direction = ParameterDirection.Input;");
                W(sb, 3, "}");

                W(sb, 0);
                W(sb, 3, "conn.Open();");
                W(sb, 3, "cmd.ExecuteNonQuery();");

                if (hasPk && pkField2 != null && table.IsPrimaryKeyIdentity)
                {
                    string pkVar = $"_{SafeName(pkField2.FieldName)}";
                    string baseCType = pkField2.CSharpType(false).TrimEnd('?');
                    W(sb, 0);
                    W(sb, 3, "if (!_isUpdate)");
                    W(sb, 4, $"{pkVar} = ({baseCType})cmd.Parameters[\"@{pkField2.FieldName}\"].Value;");
                }

                W(sb, 3, "_isDirty = false;");
                W(sb, 3, "_isUpdate = true;");
                W(sb, 2, "}");
                W(sb, 2, "#endregion");
                W(sb, 0);

                // ── Delete ────────────────────────────────────────────────────────
                if (table.PrimaryKey != null)
                {
                    var pkField = table.Fields.First(f => f.FieldName == table.PrimaryKey);
                    string pkVar = $"_{SafeName(pkField.FieldName)}";
                    string spDelete = SpName(table.TableName, "Delete");

                    W(sb, 2, "#region Delete");

                    if (!suppressComments && falseErase && hasFEField)
                    {
                        W(sb, 2, "/// <summary>");
                        W(sb, 2, $"/// The stored procedure [{spDelete}] sets [{falseEraseField}] = 1 (soft delete).");
                        W(sb, 2, "/// Records where " + falseEraseField + " is true are excluded from all queries.");
                        W(sb, 2, "/// </summary>");
                    }
                    else if (!suppressComments)
                        W(sb, 2, "/// <summary>Deletes the current record.</summary>");

                    W(sb, 2, "public void Delete()");
                    W(sb, 2, "{");
                    W(sb, 3, $"const string sp = \"[dbo].[{spDelete}]\";");
                    W(sb, 3, "using var conn = new SqlConnection(GetConnectString());");
                    W(sb, 3, "using var cmd = new SqlCommand(sp, conn);");
                    W(sb, 3, "cmd.CommandType = CommandType.StoredProcedure;");
                    W(sb, 3, $"cmd.Parameters.Add(\"@{pkField.FieldName}\", SqlDbType.{pkField.SqlDbTypeStr()}).Value = {pkVar};");
                    W(sb, 3, "conn.Open();");
                    W(sb, 3, "cmd.ExecuteNonQuery();");
                    W(sb, 2, "}");

                    W(sb, 2, "#endregion");
                    W(sb, 0);
                }
            }

            // ── GetBySQLStatement ─────────────────────────────────────────────────
            W(sb, 2, "#region GetBySQLStatement");

            if (!suppressComments) W(sb, 2, "/// <summary>Execute a raw SQL query and return a DataTable.</summary>");
            W(sb, 2, "public static DataTable? GetBySQLStatement(string sql)");
            W(sb, 2, "{");
            W(sb, 3, "using var conn = new SqlConnection(GetConnectionString());");
            W(sb, 3, "using var cmd = new SqlCommand(sql, conn) { CommandType = CommandType.Text };");
            W(sb, 3, "conn.Open();");
            W(sb, 3, "using var da = new SqlDataAdapter(cmd);");
            W(sb, 3, "var ds = new DataSet();");
            W(sb, 3, "da.Fill(ds);");
            W(sb, 3, "return ds.Tables.Count > 0 && ds.Tables[0].Rows.Count > 0 ? ds.Tables[0] : null;");
            W(sb, 2, "}");
            W(sb, 2, "#endregion");
            W(sb, 0);

            W(sb, 1, "}"); // end class
            W(sb, 0, "}"); // end namespace

            return sb.ToString();
        }

